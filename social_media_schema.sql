-- Social media drafts and publications (see docs/redes-sociales/PLAN.md, section b).
-- Run once in the Supabase SQL Editor. It only ADDS tables and a bucket:
-- no existing table is modified.

-- 1. One draft/publication per property and network
create table if not exists public.social_posts (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  property_id     bigint not null references public.properties(id) on delete cascade,
  network         text   not null check (network in ('linkedin','facebook','instagram','youtube')),
  status          text   not null default 'generando'
                  check (status in ('generando','pendiente','aprobado','publicando','publicado','error','rechazado')),
  title           text,
  body            text,
  hashtags        text[] not null default '{}',
  link            text,
  media           jsonb  not null default '[]',
  video           jsonb  not null default '{}',
  media_status    text   not null default 'pendiente' check (media_status in ('pendiente','generando','listo','error')),
  dry_run         boolean,
  payload         jsonb,
  external_id     text,
  external_url    text,
  external_extra  jsonb  not null default '{}',
  attempts        int    not null default 0,
  last_error      text,
  approved_at     timestamptz,
  approved_by     text,
  published_at    timestamptz,
  unique (property_id, network)
);
create index if not exists social_posts_status_idx on public.social_posts (status);

-- 2. Every publish attempt (audit + retries)
create table if not exists public.social_post_attempts (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  post_id     bigint not null references public.social_posts(id) on delete cascade,
  dry_run     boolean not null,
  ok          boolean not null,
  http_status int,
  error       text,
  response    jsonb
);

-- 3. Connected accounts. Tokens are AES-256-GCM encrypted by the API.
create table if not exists public.social_accounts (
  network              text primary key check (network in ('linkedin','facebook','instagram','youtube')),
  updated_at           timestamptz not null default now(),
  account_id           text not null,
  account_name         text,
  access_token_enc     text not null,
  refresh_token_enc    text,
  token_expires_at     timestamptz,
  refresh_expires_at   timestamptz,
  scopes               text[]
);

alter table public.social_posts          enable row level security;
alter table public.social_post_attempts  enable row level security;
alter table public.social_accounts       enable row level security;

-- The admin panel reads drafts and attempts directly; every write goes through
-- /api/social with the service_role key.
create policy "Admins read social posts"
  on public.social_posts for select using ( auth.role() = 'authenticated' );
create policy "Admins read social attempts"
  on public.social_post_attempts for select using ( auth.role() = 'authenticated' );
-- social_accounts: NO policies on purpose. Only service_role can read tokens.

-- 4. Public bucket for the per-network JPEGs and the videos. Platforms download
-- the images from a public URL; only service_role (and signed upload URLs
-- issued by the API) can write.
insert into storage.buckets (id, name, public)
values ('social', 'social', true)
on conflict (id) do nothing;
